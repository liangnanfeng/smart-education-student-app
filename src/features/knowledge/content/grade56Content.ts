function part(
  number: number,
  title: string,
  summary: string,
  concept: string,
  experiment: string,
  safety: string,
  challenge: string,
  keyConcepts: CoursePart['keyConcepts'] = [],
): CoursePart {
  return { id: makeCoursePartId('ael', number), number, title, summary, concept, experiment, safety, challenge, keyConcepts }
}

function concept(term: string, explanation: string, analogy: string) {
  return { term, explanation, analogy }
}
